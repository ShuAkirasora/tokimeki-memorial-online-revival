# Two ledes because there are two audiences, and the difference between them is
# the first thing either one needs to know: one has no code and is here to be
# given one, the other is holding a code somebody handed them.
LEDE_SIGNUP = """Local revival server. Make an account here, then sign in with
the client using what this page gives you."""

LEDE_REGISTER = """Local revival server. For a registration code somebody gave
you. If you do not have one, <a href="/">start here</a> instead."""


def page(
    body: str,
    message: tuple[str, str] | None = None,
    *,
    lede: str = LEDE_SIGNUP,
) -> bytes:
    banner = ""
    if message is not None:
        kind, text = message
        banner = f'<p class="msg {kind}">{text}</p>'
    # noindex because there is no version of this page that is improved by being
    # found in a search result. Somebody who should be here was told where it is;
    # robots.txt says the same thing to whatever reads that instead.
    return f"""<!DOCTYPE html>
<html lang="en">
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex, nofollow">
<title>Registration</title>
<style>{STYLE}</style>
<h1>Registration</h1>
<p class="lede">{lede}</p>
{banner}
{body}
""".encode("utf-8")


ROBOTS = b"User-agent: *\nDisallow: /\n"

# How long a /done link keeps working. Long enough to copy twenty characters and
# to come back to the tab after a distraction, short enough that the link stops
# being one before it is forgotten about in somebody's history.
TICKET_TTL = 15 * 60

EXPIRED_TICKET = (
    "That link has expired. Fill this in again with the same KONAMI ID and "
    "personal key and it will show you the same code."
)


def code_boxes(values: list[str]) -> str:
    boxes = []
    for i in range(GROUPS):
        value = html.escape(values[i]) if i < len(values) else ""
        if i:
            boxes.append("<span>-</span>")
        boxes.append(
            f'<input name="code{i}" maxlength="{codes.GROUP_LEN}" '
            f'value="{value}" autocapitalize="characters" spellcheck="false">'
        )
    return '<div class="code">' + "".join(boxes) + "</div>"


def code_shown(key: str) -> str:
    """A finished code, in the five boxes the login screen splits it into.

    Read-only inputs rather than text, for the same reason code_boxes exists:
    the player is transcribing this into five boxes that look like these, and a
    run of twenty characters is transcribed wrong.
    """
    boxes = []
    for i, group in enumerate(codes.format_code(key).split("-")):
        if i:
            boxes.append("<span>-</span>")
        boxes.append(
            f'<input value="{html.escape(group)}" readonly spellcheck="false">'
        )
    return '<div class="code">' + "".join(boxes) + "</div>"


