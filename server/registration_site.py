# The client's own words for the refusals this page can run into, so that a
# player is told here exactly what the login screen would have told them. Taken
# from the client's MsgSvNgLoginServerLogin table; see codes.py for the reasons.
REASON_TEXT = {
    codes.REASON_UNKNOWN: "入力されたレジストレーションコードは存在しません。",
    codes.REASON_EXPIRED: "レジストレーションコードの有効期限が過ぎています。",
    codes.REASON_SUSPENDED: "アカウント停止期間中です。",
}


class RegistrationSite:
    """The 登録 form, on a port a browser can reach.

    Plain HTTP on purpose, and the reason is a certificate rather than
    indifference. The client's auth endpoints are TLS because the client insists
    on it, and that certificate is 1024-bit RSA signed with SHA-1 -- which every
    current browser refuses outright, so serving this page from the same context
    would make it unreachable by the only thing that can render it. A second,
    current certificate would have to be issued against a name, and this server
    is reached by address.

    So a personal key crosses this connection in the clear, and the page says so
    rather than leaving it to be found out. What that is worth depends on where
    the browser is: on the machine running the server it is nothing, and across
    a network it is a password in plaintext. konami_id.py sets out what a
    personal key is here -- a label with a lock drawn on it, weak because the
    client's login screen imposes the shape -- which is why this is a sentence
    on the form and not a refusal to serve the page, and why the sentence says
    to pick something not used anywhere else.
    """

    def __init__(
        self,
        root: Path,
        config: ServiceConfig,
        *,
        directory: konami_id.Directory,
        table: codes.CodeTable,
        advertise_ip: str = "127.0.0.1",
    ) -> None:
        self.root = root
        self.config = config
        self.directory = directory
        self.codes = table
        self.advertise_ip = advertise_ip
        # token -> (what the next GET should draw, when it stops working). In
        # memory and gone on restart, which is the right lifetime for something
        # whose loss costs a player one more trip through the form.
        self._handoffs: dict[str, tuple[dict, float]] = {}

    # -- what the POST leaves for the GET to draw ---------------------------

    def _keep(self, **payload) -> str:
        now = time.monotonic()
        for token, (_, expires) in list(self._handoffs.items()):
            if expires <= now:
                del self._handoffs[token]
        token = secrets.token_urlsafe(16)
        self._handoffs[token] = (payload, now + TICKET_TTL)
        return token

    def _read(self, token: str) -> dict | None:
        """What that token stands for, or None. Reading does not spend it.

        Spending it on the first read would put the reload it exists to allow
        straight back into the hands of the error it exists to avoid.
        """
        kept = self._handoffs.get(token)
        if kept is None:
            return None
        payload, expires = kept
        if expires <= time.monotonic():
            del self._handoffs[token]
            return None
        return payload

    def _see_other(self, path: str, **payload) -> bytes:
        token = self._keep(**payload)
        return self._respond(
            b"", b"303 See Other", location=f"{path}?t={token}".encode("ascii")
        )

    # -- the number worth keeping -----------------------------------------

    def _note_signup(self) -> int:
        """Add one to today's count and return it. Counts, and nothing else.

        A number per day is enough to notice that something has changed, which
        is the only thing this is for. Addresses are deliberately not written
        down: they would answer no question this asks, and a list of who played
        is a thing to have to look after rather than a thing to have.
        """
        path = self.codes.dir / "registrations.json"
        try:
            counts = json.loads(path.read_text(encoding="utf-8"))
            if not isinstance(counts, dict):
                counts = {}
        except (OSError, ValueError):
            counts = {}
        today = date.today().isoformat()
        counts[today] = int(counts.get(today, 0)) + 1
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(
                json.dumps(counts, indent=2, sort_keys=True), encoding="utf-8"
            )
        except OSError as exc:
            # Worth a line, not worth failing a registration that already
            # happened: the account and the code are both already on disk.
            print(f"[register] ⚠ could not record the count: {exc}")
        return counts[today]

    # -- the self-serve path ------------------------------------------------

    def _signup(
        self, form: dict[str, str]
    ) -> tuple[tuple[str, str], tuple[str, str] | None]:
        """Make an account and hand it a code.

        Returns (message, None) or (message, (konami id, code)). The pair comes
        back separately from the message because a success here replaces the
        page rather than annotating it, and because what goes on that page is
        the stored form of the id rather than what was typed into the box.
        """
        given = form.get("konami_id", "")
        key = form.get("personal_key", "")
        if key != form.get("confirm", ""):
            return ("bad", "The two personal keys do not match."), None
        try:
            wanted = konami_id.check_id(given)
            konami_id.check_personal_key(key)
        except konami_id.InvalidId as exc:
            return ("bad", html.escape(str(exc))), None

        if self.directory.exists(wanted):
            if not self.directory.verify(wanted, key):
                # This does say the id is taken, and it is the one place on
                # this page where being unhelpful was considered and rejected:
                # somebody has to pick a different id, and cannot be told to
                # without being told why. Nothing is given away by it either --
                # the form at /register has always answered the same question
                # the same way, out of create().
                return ("bad", (
                    "ユーザ情報が正しくありません。 That KONAMI ID is taken, "
                    "and that is not its personal key. Try another id."
                )), None
            mine = self.codes.codes_of(wanted)
            if mine:
                return ("ok", (
                    f"<code>{html.escape(wanted)}</code> already has a code. "
                    "Here it is again -- nothing new was issued."
                )), (wanted, mine[0])
            # Known id, no code: the account half of an earlier attempt that
            # did not get to the code half, or one made at /konami-id. Fall
            # through and give it one.
        else:
            try:
                self.directory.create(wanted, key)
            except konami_id.InvalidId as exc:  # lost a race for the name
                return ("bad", html.escape(str(exc))), None

        # issue() then register(), which is the original's two stages run
        # end to end. Not issue(state=STATE_ACTIVE): that one belongs to the
        # operator handing a code straight to somebody, and it is register()
        # that writes the owner.
        code = self.codes.issue(state=codes.STATE_ISSUED, note="self-serve")
        reason = self.codes.register(code, wanted)
        if reason is not None:
            # Cannot happen against a code issued one line ago, so if it does
            # the table is not what this thinks it is. Put the code back and say
            # nothing specific -- there is nothing here the player can act on.
            print(f"[register] ⚠ self-serve register({code}) refused with {reason}")
            self.codes.unregister(code)
            return ("bad", "Something went wrong issuing a code. Try again."), None
        today = self._note_signup()
        print(
            f"[register] self-serve {codes.format_code(code)} -> {wanted} "
            f"({today} today)"
        )
        return ("ok", f"Account <code>{html.escape(wanted)}</code> created."), (wanted, code)

    # -- the two things the page does -------------------------------------

    def _create_id(self, form: dict[str, str]) -> tuple[str, str]:
        given = form.get("konami_id", "")
        key = form.get("personal_key", "")
        if key != form.get("confirm", ""):
            return "bad", "The two personal keys do not match."
        try:
            made = self.directory.create(given, key)
        except konami_id.InvalidId as exc:
            return "bad", html.escape(str(exc))
        print(f"[register] new KONAMI ID {made}")
        return "ok", (
            f"KONAMI ID <code>{html.escape(made)}</code> created. "
            "Now register a code below."
        )

    def _register(self, form: dict[str, str]) -> tuple[str, str]:
        given = form.get("konami_id", "")
        typed = "".join(form.get(f"code{i}", "") for i in range(GROUPS))
        key = codes.normalise(typed)
        if not self.directory.verify(given, form.get("personal_key", "")):
            # One sentence for a wrong id and for a wrong key, which is the one
            # place on this page where being unhelpful is the point.
            return "bad", "ユーザ情報が正しくありません。 That KONAMI ID and personal key do not match."
        if not codes.is_wellformed(key):
            return "bad", (
                f"A registration code is {codes.CODE_LEN} characters in "
                f"{GROUPS} groups, and only uses "
                f"<code>{codes.ALPHABET}</code>."
            )
        owner = konami_id.normalise_id(given)
        already = self.codes.owner(key)
        if already == owner:
            return "ok", (
                f"<code>{codes.format_code(key)}</code> is already registered to "
                f"<code>{html.escape(owner)}</code>. Nothing to do."
            )
        reason = self.codes.register(key, owner)
        if reason is not None:
            return "bad", html.escape(REASON_TEXT.get(reason, f"reason {reason}"))
        print(f"[register] {codes.format_code(key)} registered to {owner}")
        return "ok", (
            f"<code>{codes.format_code(key)}</code> is registered to "
            f"<code>{html.escape(owner)}</code>. Sign in on the client with that "
            "KONAMI ID, that personal key, and this code."
        )

    # -- http -------------------------------------------------------------

    def _respond(
        self,
        body: bytes,
        status: bytes = b"200 OK",
        content_type: bytes = b"text/html; charset=utf-8",
        location: bytes | None = None,
    ) -> bytes:
        head = (
            b"HTTP/1.1 " + status + b"\r\n"
            b"Server: TokimekiOL-Local-Registration\r\n"
            b"Content-Type: " + content_type + b"\r\n"
            b"Cache-Control: no-store\r\n"
        )
        if location is not None:
            head += b"Location: " + location + b"\r\n"
        return (
            head + b"Connection: close\r\n"
            b"Content-Length: " + str(len(body)).encode("ascii") + b"\r\n\r\n" + body
        )

    def _handle_request(
        self,
        method: str,
        path: str,
        form: dict[str, str],
        query: dict[str, str] | None = None,
    ) -> bytes:
        query = query or {}
        if method != "POST":
            # Every path is spelled out. An earlier version answered anything
            # that was not a POST with the form, which made /robots.txt a page
            # of HTML -- the one file whose whole job is to not be that.
            if path == "/robots.txt":
                return self._respond(ROBOTS, content_type=b"text/plain; charset=utf-8")
            if path == "/done":
                shown = self._read(query.get("t", ""))
                if shown is None:
                    return self._respond(page(signup(), ("bad", EXPIRED_TICKET)))
                return self._respond(
                    page(ticket(shown["owner"], shown["code"]), shown["banner"])
                )
            if path in ("/", "/signup"):
                # An expired handoff draws the empty form and says nothing. The
                # values behind it are half a minute of typing, and there is no
                # message about them that is more use than the form itself.
                again = self._read(query.get("t", "")) or {}
                return self._respond(
                    page(signup(again.get("keep")), again.get("banner"))
                )
            if path in ("/register", "/konami-id"):
                again = self._read(query.get("t", "")) or {}
                return self._respond(
                    page(
                        forms(again.get("keep")),
                        again.get("banner"),
                        lede=LEDE_REGISTER,
                    )
                )
            return self._respond(page(signup()), b"404 Not Found")

        # The personal key is never echoed back into the page; every other field
        # is, so a rejected form can be corrected rather than retyped.
        keep = {k: v for k, v in form.items() if "key" not in k and k != "confirm"}

        if path == "/signup":
            message, made = self._signup(form)
            if made is None:
                return self._see_other("/signup", keep=keep, banner=message)
            owner, code = made
            return self._see_other("/done", owner=owner, code=code, banner=message)

        # The two-stage path. What it decides is untouched -- these are the same
        # two calls, and reason 24 is reachable through them exactly as before --
        # but it hands the answer over the same way the self-serve path does. A
        # page that cannot be gone back to is not better here for being the
        # older of the two.
        if path == "/konami-id":
            message = self._create_id(form)
        elif path == "/register":
            message = self._register(form)
        else:
            return self._respond(page(signup()), b"404 Not Found")
        return self._see_other("/register", keep=keep, banner=message)

    async def handle(
        self, reader: asyncio.StreamReader, writer: asyncio.StreamWriter
    ) -> None:
        try:
            head = await asyncio.wait_for(reader.readuntil(b"\r\n\r\n"), timeout=30.0)
        except (asyncio.TimeoutError, asyncio.IncompleteReadError, ValueError):
            writer.close()
            return
        try:
            lines = head.decode("latin1").split("\r\n")
            method, target, *_ = lines[0].split(" ")
            path, _, raw_query = target.partition("?")
            query = {k: v[0] for k, v in parse_qs(raw_query).items()}
            length = 0
            for line in lines[1:]:
                name, _, value = line.partition(":")
                if name.strip().lower() == "content-length":
                    length = int(value.strip() or 0)
            # Bounded because this reads whatever the peer says is coming, and
            # the largest honest form here is a few hundred bytes.
            body = await reader.readexactly(min(length, 8192)) if length else b""
            form = {
                k: v[0]
                for k, v in parse_qs(body.decode("utf-8", "replace")).items()
            }
            response = self._handle_request(method, path, form, query)
        except Exception as exc:  # a malformed request is not a reason to die
            print(f"[register] bad request: {type(exc).__name__}: {exc}")
            response = self._respond(page(signup()), b"400 Bad Request")
        writer.write(response)
        try:
            await writer.drain()
        except Exception:
            pass
        writer.close()

    async def run(self) -> asyncio.AbstractServer:
        server = await asyncio.start_server(
            self.handle, self.config.host, self.config.port
        )
        print(
            f"[register] 登録 form on http://{self.advertise_ip}:{self.config.port}/"
        )
        return server
