"""The local stand-in for the website 登録 happened on.

A registration code in the box did not work on its own. The player went to
KONAMI's site, signed in with their KONAMI ID, typed the code from the box, and
only then would the login screen let them in -- and the client still carries the
sentences that step produced, one for a code nobody has claimed and one for a
code that needs claiming again. codes.py sets out how those sentences are the
evidence for the step.

Nothing of that page survives to copy, and nothing needs to: what is being
reproduced is the step, not KONAMI's markup. So this is a plain form on a plain
port, with the two things their site did and nothing else --

    make a KONAMI ID          an id and a personal key, which is what the
                              client's login screen asks for
    登録 a code               bind one code to one KONAMI ID, which is what
                              turns it from `issued` into `active`

-- and no third thing. There is no email step, because there is nobody to mail:
the address on KONAMI's form existed to prove a person could be reached, and a
server for the room it is running in has no use for that proof. See the README
on why this is not meant to face a network.

  One form, two steps
  -------------------
  Those two steps are one form for the player. KONAMI's sequence had a code
  arrive in a printed box before any of this began, and here there is no box: an
  id and a personal key are typed, and the code is generated and bound in the
  same request.

  Nothing about the model moves. The handler calls issue() and then register(),
  the same two calls in the same order, and a code still passes through `issued`
  on its way to `active` -- what is gone is the wait in between, which existed
  only because the code had been printed months earlier. The evidence for the
  two stages is in the client's own refusal table and is set out at the top of
  codes.py; it is about what the original could tell apart, not about how long a
  code sat between the stages.

  The stages stay separately reachable at /register, and not only for the tests.
  A code an operator generated by hand and handed to somebody has no other way
  in, and reason 24 (レジストレーションコードが登録されていません) has no other
  way to be produced.

  Signing up twice
  ----------------
  Asking for an account that already exists, with the personal key that opens
  it, shows the code that account already has rather than issuing a second one.
  That is one answer to three separate questions -- a reloaded success page, a
  player who lost the code, and somebody collecting codes -- and it is why
  nothing on this page is unrecoverable. It does mean the code can be retrieved
  by whoever knows the id and the key, which is a real cost and a small one:
  those two already open the account.

  The back button
  ---------------
  Nothing either form does is answered with a page. Every outcome is a 303 to a
  GET -- /done for a code, back to /signup or /register for anything else -- and
  what that GET should draw waits for TICKET_TTL under a token in memory.

  A page that *is* the answer to a POST cannot be returned to. This server sends
  no-store, so the browser has nothing to go back to and offers to send the form
  again instead, which arrives as a wall of text about resubmitting a form on
  the way back to a page the player had already been told to write down. Making
  the resubmission harmless was not enough, because the player never gets as far
  as finding out that it is.

  ⚠️ The refusals need this as much as the code does, which is not obvious and
  was got wrong once. A rejected form looks like a page nobody returns to --
  they are about to correct it and send it again -- but it stays in the history
  either way, and every later press of the back button has to walk over it. One
  mistyped id is enough to put it there.

  What is left is a pair of ordinary pages: back and reload both work, and /done
  is a link that can sit in a tab while twenty characters are copied out of it.
  It expires, and losing it is not losing the code -- the form gives the same one
  back to the same id and key, which is why this is safe to keep in memory and
  to throw away on restart.

  Language
  --------
  The page is written in English, and the field labels are in Japanese, and that
  split is deliberate rather than sloppy. A player is copying values between this
  page and the client's login screen, and that screen says KONAMI ID,
  パーソナルキー and レジストレーションコード; a label that does not match the
  box it corresponds to is a page that has to be decoded before it can be used.
  Everything the page says in its own voice is in English, as the rest of this
  tree is.

  ⚠️ 登録 is not one of those labels, and had been used as a verb on the page --
  "登録 a registration code", a button reading 登録 -- until it was noticed that
  it matches nothing the player can see. The login screen has three fields and
  no such button, and the step it names happened on a website whose markup does
  not survive. So the word stays in this file's prose and in its log lines,
  where it names a historical step for whoever is reading the code, and it is
  English wherever the page is speaking to a player. The one place a player is
  shown 登録 is inside 「レジストレーションコードが登録されていません」, which is
  quoted because it is what the client itself will say to them.
"""

